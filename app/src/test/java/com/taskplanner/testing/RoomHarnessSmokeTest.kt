package com.taskplanner.testing

import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.taskplanner.data.local.AppDatabase
import com.taskplanner.data.model.User
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * Proves the JVM test harness can open a real Room database: the repository, backup and sync tests
 * rely on it instead of mocked DAOs, so the production SQL is actually executed.
 */
@RunWith(RobolectricTestRunner::class)
class RoomHarnessSmokeTest {

    @Test
    fun `room opens an in-memory database and runs dao sql`() = runTest {
        val context = ApplicationProvider.getApplicationContext<android.content.Context>()
        val db = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        try {
            val userDao = db.userDao()
            val id = userDao.insertUser(User(email = "smoke@example.com", name = "smoke"))
            assertTrue("autogenerated id expected", id > 0)
            assertEquals(1, userDao.getAllUsersOnce().size)

            val taskDao = db.taskDao()
            val taskId = taskDao.insertTask(
                com.taskplanner.data.model.Task(title = "smoke", description = "", userId = id)
            )
            assertTrue(taskId > 0)
            assertEquals("smoke", taskDao.getTaskById(taskId)?.title)
        } finally {
            db.close()
        }
    }

    /**
     * The screens observe DAO Flows, so the harness has to deliver them; with Room's default
     * background executors Robolectric's per-thread SQLite handles swallow the emissions.
     */
    @Test
    fun `dao flows reach collectors`() = kotlinx.coroutines.runBlocking {
        val context = ApplicationProvider.getApplicationContext<android.content.Context>()
        val fixture = AppFixture(context)
        try {
            val user = fixture.signIn(email = "flow@example.com")
            val flow = fixture.taskDao.getActiveTasks(user.id)
            assertEquals(emptyList<String>(), flow.first().map { it.title })

            fixture.addTask(user.id, "Shown in the list")

            assertEquals(listOf("Shown in the list"), flow.first().map { it.title })
        } finally {
            fixture.close()
        }
    }
}
